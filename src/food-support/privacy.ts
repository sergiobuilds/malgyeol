export function containsLikelyPii(value: string): boolean {
  const normalized = value.normalize('NFKC');
  return /(?:^|\D)01[016789][ -]?\d{3,4}[ -]?\d{4}(?:\D|$)/.test(normalized)
    || /[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}/i.test(normalized)
    || /\b\d{6}[ -]?\d{7}\b/.test(normalized)
    || /(?:주소|배송지|사는 곳|거주지|내 이름|전화번호|연락처)/.test(normalized)
    || /\b\d{5}\b.*(?:로|길|동|호|아파트|빌라)/.test(normalized)
    // 도로명 주소는 "주소"라는 표지어 없이 말하는 경우가 더 많다.
    // 행정구역 + 도로명 + 건물번호 조합은 상품명으로 쓰일 가능성보다
    // 배송지일 가능성이 월등히 높으므로 외부 모델·판매처 전송 전에 닫는다.
    || /(?:서울(?:특별시|시)?|부산(?:광역시)?|대구(?:광역시)?|인천(?:광역시)?|광주(?:광역시)?|대전(?:광역시)?|울산(?:광역시)?|세종(?:특별자치시)?|제주(?:특별자치도)?|경기(?:도)?|강원(?:특별자치도|도)?|충청[남북]도?|전라[남북]도?|경상[남북]도?)\s*[가-힣]{1,20}(?:시|군|구)\s*[가-힣0-9·._-]{1,40}(?:로|길)\s*\d{1,5}(?:-\d{1,5})?/.test(normalized)
    || /[가-힣0-9·._-]{2,40}(?:로|길)\s*\d{1,5}(?:-\d{1,5})?(?:\s*\d{1,4}호)?/.test(normalized)
    || /[가-힣]{1,20}(?:읍|면|동|리)\s*\d{1,5}(?:-\d{1,5})?(?:\s*\d{1,4}호)?/.test(normalized);
}
